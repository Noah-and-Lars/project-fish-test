// What this browser has played, for "Continue playing" and the NEW / UPDATED badges, worked out as the real
// site does. This site shares its browser storage with the real arcade (same address), so it reads the real
// site's list ('arcade-played') but only ever writes its own ('arcade-test-played'), for Steelhead: Dead Ground.
window.Arcade = {
  played() { return Object.assign({}, readSave('arcade-played', true) || {}, readSave('arcade-test-played', true) || {}); },
  markPlayed(id) {
    const p = readSave('arcade-test-played', true) || {};
    p[id] = new Date().toISOString();
    try { localStorage.setItem('arcade-test-played', JSON.stringify(p)); } catch (e) {}
  },
  recent(n) {
    const p = this.played();
    return GAMES.filter(g => p[g.id]).sort((a, b) => Date.parse(p[b.id]) - Date.parse(p[a.id])).slice(0, n);
  },
  // NEW until you've played it (for its first month); UPDATED if it changed since you last played
  badge(g) {
    if (g.badge) return g.badge;
    const last = this.played()[g.id];
    if (!last) return Date.now() - Date.parse(g.added) < 30 * 864e5 ? 'NEW' : null;
    return Date.parse(g.updated) > Date.parse(last) ? 'UPDATED' : null;
  },
  stat() { return null; },
};

